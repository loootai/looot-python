"""Writes src/looot/_async_client.py (AsyncLooot) from src/looot/_client.py (Looot).

Run after any change to _client.py:  python scripts/gen_async.py
tests/test_async.py fails when the committed file differs from what this script writes.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "src" / "looot" / "_client.py"
TARGET = ROOT / "src" / "looot" / "_async_client.py"

HEADER = '''"""AsyncLooot, the asynchronous client for the looot REST API.

Generated by scripts/gen_async.py from _client.py. Do not edit by hand: edit _client.py, then
run ``python scripts/gen_async.py``.
"""
'''

SYNC_METHODS = {"__init__", "__repr__"}


def convert(source: str) -> str:
    """Returns the async client source for the sync client source."""
    body = source.split('"""', 2)[2].lstrip("\n")
    out = []
    for line in body.splitlines():
        line = line.replace("import time", "import asyncio\nimport time")
        line = line.replace("Iterator", "AsyncIterator")
        line = line.replace("httpx.Client(", "httpx.AsyncClient(")
        line = line.replace("httpx.BaseTransport", "httpx.AsyncBaseTransport")
        line = line.replace("time.sleep", "asyncio.sleep")
        line = line.replace("class Looot:", "class AsyncLooot:")
        line = line.replace("Synchronous client", "Asynchronous client")
        line = line.replace('__all__: List[str] = ["Looot"]', '__all__: List[str] = ["AsyncLooot"]')
        line = line.replace("def __enter__(self) -> \"Looot\":", "def __aenter__(self) -> \"AsyncLooot\":")
        line = line.replace("def __exit__(", "def __aexit__(")
        line = line.replace("self._http.close()", "await self._http.aclose()")
        line = line.replace("self.close()", "await self.close()")
        line = re.sub(r"^(\s*)self\._sleep\(", r"\1await self._sleep(", line)
        line = re.sub(r"((?:\breturn|=)\s+)self\.(_http\.request|_?[a-z]\w*)\(", r"\1await self.\2(", line)
        match = re.match(r"^    def (\w+)\(", line)
        if match and match.group(1) not in SYNC_METHODS:
            line = "    async " + line[4:]
        out.append(line)
    return HEADER + "\n" + "\n".join(out) + "\n"


def main() -> int:
    """Writes the file, or with --check exits 1 when it is out of date."""
    generated = convert(SOURCE.read_text())
    if "--check" in sys.argv:
        if TARGET.read_text() != generated:
            print("src/looot/_async_client.py is out of date: run python scripts/gen_async.py")
            return 1
        return 0
    TARGET.write_text(generated)
    return 0


if __name__ == "__main__":
    sys.exit(main())
